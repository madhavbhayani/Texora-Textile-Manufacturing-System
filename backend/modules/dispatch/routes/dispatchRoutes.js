'use strict';
const express=require('express');
const authenticate=require('../../auth/middleware/authenticate');
const authorize=require('../../auth/middleware/authorize');
const c=require('../controllers/dispatchController');
const AppError=require('../../../shared/errors/AppError');
const router=express.Router();
router.use(authenticate);
const dispatchRole=authorize('DISPATCH_OFFICER','OWNER');
router.get('/dashboard',dispatchRole,c.dashboard);
router.get('/queue',dispatchRole,c.queue);
router.get('/orders/:orderId',dispatchRole,c.orderDetail);
router.get('/eligible-rolls',dispatchRole,c.eligibleRolls);
router.get('/shipments',dispatchRole,c.shipments);
router.post('/shipments',dispatchRole,c.createShipment);
router.get('/shipments/:shipmentId',dispatchRole,c.shipment);
router.post('/shipments/:shipmentId/items',dispatchRole,c.addRolls);
router.delete('/shipments/:shipmentId/items/:itemId',dispatchRole,c.removeRoll);
router.post('/shipments/:shipmentId/pack',dispatchRole,c.pack);
router.post('/shipments/:shipmentId/ship',dispatchRole,c.ship);
router.post('/shipments/:shipmentId/deliver',dispatchRole,c.deliver);
router.post('/shipments/:shipmentId/cancel',dispatchRole,c.cancel);
router.post('/shipments/:shipmentId/invoice',dispatchRole,c.createInvoice);
router.get('/invoices',dispatchRole,c.invoices);
router.get('/notifications',dispatchRole,c.notifications);
router.get('/my-invoices',authorize('BUYER'),c.myInvoices);
router.post('/my-invoices/:invoiceId/payments',authorize('BUYER'),c.buyerPayment);
router.get('/invoices/:invoiceId/pdf',c.invoicePdf);
router.get('/invoices/:invoiceId',dispatchRole,c.invoice);
router.use((req,res,next)=>next(new AppError(404,'NOT_FOUND','Dispatch resource was not found.')));
module.exports=router;
